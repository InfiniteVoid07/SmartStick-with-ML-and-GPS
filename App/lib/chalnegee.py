def ecc_add(p1, p2):
    if p1 == p2:
        denom = 2 * p1[1]
        inv = modinv(denom % P, P)
        if inv is None:
            raise Exception(f"No modular inverse for {denom} mod {P}")
        l = ((3 * p1[0]**2 + A) * inv) % P
    else:
        denom = (p2[0] - p1[0]) % P
        inv = modinv(denom, P)
        if inv is None:
            raise Exception(f"No modular inverse for {denom} mod {P}")
        l = ((p2[1] - p1[1]) * inv) % P

    x3 = (l**2 - p1[0] - p2[0]) % P
    y3 = (l * (p1[0] - x3) - p1[1]) % P
    return (x3, y3)


def ecc_mul(k, point):
    result = point
    for _ in range(k-1):
        result = ecc_add(result, point)
    return result

