# Round constants
RCON = [0x01]
for _ in range(1, 15):
    RCON.append((RCON[-1] << 1) ^ (0x11B if RCON[-1] & 0x80 else 0))

def sub_word(w): return [SBOX[b] for b in w]
def rot_word(w): return w[1:] + w[:1]
def xor_bytes(a, b): return [x ^ y for x, y in zip(a, b)]

def key_expansion(key):
    key = list(key)
    w = [key[i:i + 4] for i in range(0, len(key), 4)]
    for i in range(Nk, Nb * (Nr + 1)):
        temp = w[i - 1]
        if i % Nk == 0:
            temp = xor_bytes(sub_word(rot_word(temp)), [RCON[i // Nk - 1], 0, 0, 0])
        elif Nk > 6 and i % Nk == 4:
            temp = sub_word(temp)
        w.append(xor_bytes(w[i - Nk], temp))
    return w

def add_round_key(s, w, rnd):
    for r in range(4):
        for c in range(4):
            s[r][c] ^= w[rnd * Nb + c][r]
    return s

def sub_bytes(s): return [[SBOX[b] for b in row] for row in s]
def shift_rows(s): return [[s[r][(c + r) % 4] for c in range(4)] for r in range(4)]

def xtime(a): return (((a << 1) ^ 0x1B) & 0xFF) if (a & 0x80) else a << 1

def mix_columns(s):
    for i in range(4):
        a = s[0][i]; b = s[1][i]; c = s[2][i]; d = s[3][i]
        s[0][i] = xtime(a) ^ xtime(b)^ b ^ c ^ d
        s[1][i] = a ^ xtime(b) ^ xtime(c)^ c ^ d
        s[2][i] = a ^ b ^ xtime(c) ^ xtime(d)^ d
        s[3][i] = xtime(a)^ a ^ b ^ c ^ xtime(d)
    return s

def bytes2matrix(b): return [list(b[i::4]) for i in range(4)]
def matrix2bytes(m): return bytes(sum(zip(*m), ()))

def pad(plaintext):
    pad_len = 16 - len(plaintext) % 16
    return plaintext + bytes([pad_len] * pad_len)

def unpad(plaintext):
    pad_len = plaintext[-1]
    return plaintext[:-pad_len]

def encrypt_block(block, key_schedule):
    s = bytes2matrix(block)
    s = add_round_key(s, key_schedule, 0)
    for rnd in range(1, Nr):
        s = sub_bytes(s)
        s = shift_rows(s)
        s = mix_columns(s)
        s = add_round_key(s, key_schedule, rnd)
    s = sub_bytes(s)
    s = shift_rows(s)
    s = add_round_key(s, key_schedule, Nr)
    return matrix2bytes(s)

